# Process the video frame by frame
while cap.isOpened():
    # Read the next frame
    success, frame = cap.read()

    # Stop when video ends
    if not success:
        break

    # Track bottles using ByteTrack
    results = model.track(
        frame,
        persist=True,
        tracker="bytetrack.yaml",
        conf=0.15,
        iou=0.45,
        classes=[39],
        imgsz=1280,
        device=device,
        verbose=False
    )

    # Initialize visible bottle count as an integer
    bottle_count = 0

    # Get detected boxes
    boxes = results[0].boxes

    # Check whether tracking IDs are available
    if boxes.id is not None:
        # Get tracking IDs
        tracks_ids = boxes.id.cpu().numpy().astype(int)

        # Process each tracked bottle
        for box, track_id in zip(boxes, tracks_ids):
            # Get bottle coordinates
            x1, y1, x2, y2 = box.xyxy[0].cpu().numpy().astype(int)

            # Calculate bottle center
            center_x = (x1 + x2) // 2
            center_y = (y1 + y2) // 2

            # Check whether bottle is inside fridge ROI
            if roi_x1 <= center_x <= roi_x2 and roi_y1 <= center_y <= roi_y2:
                # Increase visible bottle count
                bottle_count += 1

                # Draw bottle bounding box
